import type { Model } from "../model/types.ts";

// Слой DTO: пометка «сырой payload редактора» (аудит 65 C4, задача 187-c4 п.3).
//
// model_get(detail=full), project_export_plan и project_import_plan отдают и
// принимают СЫРОЙ формат модели сайта remplanner (project.copy сервера):
//   - единицы — САНТИМЕТРЫ сайта (координаты, толщины, размеры), как их хранит
//     и отдаёт сам сайт; компактный публичный API MCP переводит в миллиметры;
//   - формат принадлежит сайту и может измениться с его обновлением — MCP не
//     гарантирует совместимость сырого payload между версиями сайта;
//   - это осознанный escape hatch: экспорт/импорт проекта и полный дамп модели
//     для отладки. Публичный контракт компактных инструментов от него не зависит.
// Версия envelope и замена публичных кодов — отдельное согласованное изменение
// API (не рефакторинг); пока версия формата не вводится.

/**
 * Копия сырой модели редактора (deep clone) для публичного ответа
 * model_get(detail=full). Единицы — см сайта, формат — сайта (см. шапку файла).
 */
export function rawEditorPayload(model: Model): Model {
  return JSON.parse(JSON.stringify(model)) as Model;
}
