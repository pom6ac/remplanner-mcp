/**
 * B5+B6 (аудит 65): ресурсные лимиты входа — в одном месте.
 * Значения с большим запасом против реальных планов (типовая квартира —
 * десятки стен/предметов, координаты до тысяч см): лимиты отсекают аномальные
 * входы (сотни тысяч точек, гигантские координаты, длинные строки, узкие
 * полигоны), которые могут забить память/CPU процесса или уйти в редактор.
 */

